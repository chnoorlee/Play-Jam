export function translateUI(text, translatePart = part => part) {
  if (typeof text !== 'string') return text;
  const source = text.trim();
  const english = localize(source, translatePart);
  return english === source ? text : text.replace(source, () => english);
}

function localize(source, translatePart) {
  if (Object.hasOwn(strings, source)) return strings[source];
  if (!/[\u3400-\u9fff]/u.test(source)) return source;
  const part = value => strings[value] ?? translatePart(value);
  let match;
  if ((match = /^已投递 (\d+) \/ 3 封信$/.exec(source))) return `${match[1]} of 3 letters delivered`;
  if ((match = /^站牌记录 (\d+) \/ 2$/.exec(source))) return `Board notes ${match[1]} / 2`;
  if ((match = /^与(.+)交谈$/.exec(source))) return `Talk to ${part(match[1])}`;
  if ((match = /^查看(.+)线索$/.exec(source))) return `Hints for the ${part(match[1])}`;
  if ((match = /^前往(.+)$/.exec(source))) return `Go to the ${part(match[1])}`;
  if ((match = /^(.+)：(.+)，转动$/.exec(source))) return `${part(match[1])}: ${part(match[2])}. Turn.`;
  if ((match = /^(.+)的回信，已经放进邮包。$/.exec(source))) return `${part(match[1])}’s reply is in your satchel.`;
  if ((match = /^许渡的旧邮包 · 回信 (\d+) \/ 3 · 纪念物 (\d+) \/ 3$/.exec(source))) return `Xu Du’s satchel · Replies ${match[1]}/3 · Keepsakes ${match[2]}/3`;
  if ((match = /^便笺 (\d+)$/.exec(source))) return `Note ${match[1]}`;
  if ((match = /^(.+)留下$/.exec(source))) return `From ${part(match[1])}`;
  if ((match = /^纪念物：(.+)$/.exec(source))) return `Keepsake: ${part(match[1])}`;
  if ((match = /^(.+) · 已送达 (\d+) \/ 3$/.exec(source))) return `${part(match[1])} · Delivered ${match[2]}/3`;
  if (source.includes(' · ')) {
    const pieces = source.split(' · ');
    const translated = pieces.map(part);
    if (translated.every(value => !/[\u3400-\u9fff]/u.test(value))) return translated.join(' · ');
  }
  return source;
}
