from pathlib import Path
from random import Random

from PIL import Image, ImageDraw


SIZE = 256
SCALE = 2
INK = "#203741"
PAPER = "#f1dfb5"
BRASS = "#d49a53"
JADE = "#527a70"
RUST = "#ac5d49"
SKIN = "#dfad83"
SHADOW = "#b97259"


class Print:
    def __init__(self, field, halo, seed):
        self.image = Image.new("RGB", (SIZE * SCALE, SIZE * SCALE), PAPER)
        self.draw = ImageDraw.Draw(self.image)
        self.random = Random(seed)
        self.rect(8, 8, 248, 248, self.ink_mix(field, PAPER, 0.23))
        self.rect(12, 12, 244, 244, field)
        self.oval(28, 25, 227, 224, halo)
        self.oval(25, 22, 230, 227, None, self.ink_mix(halo, PAPER, 0.45))
        screened = self.ink_mix(field, halo, 0.58)
        for y in range(23, 232, 5):
            for x in range(21 + y % 2, 239, 5):
                if (x - 123) ** 2 + (y - 114) ** 2 > 104**2:
                    self.oval(x, y, x + 0.65, y + 0.55, screened)

    @staticmethod
    def ink_mix(base, other, weight):
        first = bytes.fromhex(base[1:])
        second = bytes.fromhex(other[1:])
        channels = (round(a * (1 - weight) + b * weight) for a, b in zip(first, second))
        return tuple(channels)

    def rect(self, left, top, right, bottom, fill):
        self.draw.rectangle(tuple(v * SCALE for v in (left, top, right, bottom)), fill=fill)

    def oval(self, left, top, right, bottom, fill, outline=None, width=1):
        self.draw.ellipse(tuple(v * SCALE for v in (left, top, right, bottom)),
                          fill=fill, outline=outline, width=round(width * SCALE))

    def line(self, points, fill, width=1):
        self.draw.line([(x * SCALE, y * SCALE) for x, y in points],
                       fill, max(1, round(width * SCALE)), joint="curve")

    def shape(self, start, segments, fill=None, stroke=None, width=1):
        points = [start]
        for segment in segments:
            if len(segment) == 2:
                points.append(segment)
                continue
            x0, y0 = points[-1]
            x1, y1, x2, y2, x3, y3 = segment
            for step in range(1, 15):
                t = step / 14
                u = 1 - t
                points.append((
                    u**3 * x0 + 3 * u**2 * t * x1 + 3 * u * t**2 * x2 + t**3 * x3,
                    u**3 * y0 + 3 * u**2 * t * y1 + 3 * u * t**2 * y2 + t**3 * y3,
                ))
        if fill:
            self.draw.polygon([(x * SCALE, y * SCALE) for x, y in points], fill=fill)
        if stroke:
            self.line(points + ([points[0]] if fill else []), stroke, width)

    def hatching(self, strokes, color, width=1):
        for start, end in strokes:
            self.line((start, end), color, width)

    def finish(self, output):
        for edge in (0, 248):
            self.rect(0, edge, 256, edge + 7.5, PAPER)
            self.rect(edge, 0, edge + 7.5, 256, PAPER)

        pixels = self.image.load()
        for y in range(self.image.height):
            for x in range(self.image.width):
                variation = self.random.choice((-10, -6, -3, 0, 0, 2, 5, 9))
                pixels[x, y] = tuple(max(0, min(255, value + variation)) for value in pixels[x, y])
        for _ in range(13000):
            x = self.random.randrange(2, self.image.width - 2)
            y = self.random.randrange(2, self.image.height - 2)
            red, green, blue = pixels[x, y]
            if self.random.random() < 0.6:
                tint = (min(255, red + 32), min(255, green + 26), min(255, blue + 14))
            else:
                tint = (max(0, red - 24), max(0, green - 21), max(0, blue - 15))
            self.draw.line(((x, y), (x + self.random.randrange(1, 3), y)), fill=tint)
        rendered = self.image.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
        rendered.save(output, format="WEBP", quality=89, method=6)


