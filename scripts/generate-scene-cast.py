CAST = {"shen": shen, "cao": cao, "ye": ye, "lan": lan, "xu": xu}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("characters", nargs="*", help="Names to republish, or leave blank for all cast.")
    args = parser.parse_args()
    names = args.characters or CAST
    invalid = set(names) - CAST.keys()
    if invalid:
        parser.error(f"Unknown character(s): {', '.join(sorted(invalid))}")
    output = Path(__file__).resolve().parents[1] / "src" / "art" / "cast"
    output.mkdir(parents=True, exist_ok=True)
    for seed, (name, paint) in enumerate(CAST.items()):
        if name in names:
            illustration = Painting()
            paint(illustration)
            illustration.finish(output / f"{name}.webp", seed)


if __name__ == "__main__":
    main()
