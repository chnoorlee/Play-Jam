from PIL import Image, ImageColor, ImageDraw


WIDTH, HEIGHT = 360, 520
SCALE = 3
INK = "#21292c"
FACE_EDGE = "#533c37"


def blend(first, second, mix):
    return tuple(
        round(a + (b - a) * mix)
        for a, b in zip(ImageColor.getrgb(first), ImageColor.getrgb(second))
    )


class Painting:
    def __init__(self):
        self.image = Image.new("RGBA", (WIDTH * SCALE, HEIGHT * SCALE))
        self.draw = ImageDraw.Draw(self.image)

    def path(self, coordinates, fill=None, stroke=None, width=1):
        """Trace a contour from an initial point, line ends and cubic curves."""
        start, *segments = coordinates
        points = [start]
        for segment in segments:
            if len(segment) == 2:
                points.append(segment)
                continue
            x0, y0 = points[-1]
            x1, y1, x2, y2, x3, y3 = segment
            for step in range(1, 17):
                t = step / 16
                u = 1 - t
                points.append((
                    u**3 * x0 + 3 * u**2 * t * x1 + 3 * u * t**2 * x2 + t**3 * x3,
                    u**3 * y0 + 3 * u**2 * t * y1 + 3 * u * t**2 * y2 + t**3 * y3,
                ))
        scaled = [(round(x * SCALE), round(y * SCALE)) for x, y in points]
        if fill:
            self.draw.polygon(scaled, fill=fill)
        if stroke:
            contour = scaled + ([scaled[0]] if fill else [])
            self.draw.line(contour, fill=stroke, width=max(1, round(width * SCALE)), joint="curve")

    def ellipse(self, box, fill, outline=None, width=1):
        self.draw.ellipse(tuple(round(value * SCALE) for value in box), fill=fill,
                          outline=outline, width=max(1, round(width * SCALE)))

    def finish(self, output, seed):
        rendered = self.image.resize((432, 624), Image.Resampling.LANCZOS)
        pixels = rendered.load()
        random = Random(seed)
        for y in range(rendered.height):
            for x in range(rendered.width):
                red, green, blue, alpha = pixels[x, y]
                if alpha == 255:
                    grain = random.randrange(-4, 5)
                    pixels[x, y] = (
                        min(255, max(0, red + grain)),
                        min(255, max(0, green + grain)),
                        min(255, max(0, blue + grain)),
                        alpha,
                    )
        rendered.save(output, format="WEBP", quality=91, method=6)


