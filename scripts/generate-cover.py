def spruce(x, y, height):
    stroke([(x, y), (x, y - height * .88)], "#634c3a", 4)
    for tier in range(3):
        top = y - height * (1 - tier * .195)
        fan = height * (.13 + tier * .05)
        heel = top + height * .46
        shape([(x, top), (x - fan, heel), (x + fan, heel - 1)], "#375e50")
        shape([(x, top), (x, heel), (x + fan, heel - 1)], "#29483f")


